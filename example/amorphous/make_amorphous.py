#!/usr/bin/env python3
"""
K.NAKADA, kengo.nakada@gmail.com
make_amorphous.py

Fe–Si–B アモルファス初期構造を Packmol により生成するための
入力ファイル (packmol.inp) を作成するスクリプト。

本スクリプトは、以下の 3 点を外部入力とする：

    1. 化学量論比（整数比）
    2. 密度 [g/cm^3] または 数密度 [1/Å^3] のいずれか一方
    3. セル内の総原子数 N_tot

Packmol は密度・化学量論比の概念を持たないため、本スクリプト側で
原子数とセル一辺長 L を計算し、Packmol 形式の inside box 指定に変換する。
"""
from typing import Any, Dict, List, Optional, Union, Tuple, Callable, Sequence
from rmc_dft.packmol.packmol import Packmol

# -------------------------------------------------------------
result_xyz_file = "FeSiB_amorphous.xyz"
Fe_xyz_file = "Fe.xyz"
Si_xyz_file = "Si.xyz"
B_xyz_file = "B.xyz"


def compute_element_counts(
    N_tot: int,
) -> Tuple[int, int, int]:
    """総原子数から Fe, Si, B の原子数を決定する。

    化学量論比 RATIO_Fe, RATIO_Si, RATIO_B は「原子数比」であり、
    密度・セル体積とは無関係に原子配分だけを決める。

    N_tot に対する各元素の原子数は次式で計算される：

        N_X = N_tot × (RATIO_X / (RATIO_Fe + RATIO_Si + RATIO_B))

    四捨五入により総和と N_tot が一致しなくなる場合があるため、
    誤差は Fe に割り当てて補正する。

    Args:
        N_tot (int):
            セル内の総原子数。

    Returns:
        Tuple[int, int, int]:
            (N_Fe, N_Si, N_B)
            各元素の原子数。
    """
    ratio_sum = RATIO_Fe + RATIO_Si + RATIO_B

    N_Fe_f = N_tot * RATIO_Fe / ratio_sum
    N_Si_f = N_tot * RATIO_Si / ratio_sum
    N_B_f = N_tot * RATIO_B / ratio_sum

    N_Fe = round(N_Fe_f)
    N_Si = round(N_Si_f)
    N_B = round(N_B_f)

    diff = N_tot - (N_Fe + N_Si + N_B)
    if diff != 0:
        N_Fe += diff

    return N_Fe, N_Si, N_B


def write_packmol_input(
    packmol: Packmol,
    filename: str,
    N_tot: int,
    symbols: Optional[List[str]] = None,
    ratios: Optional[List[int]] = None,
    rho_g_cm3: Optional[float] = None,
    n_per_A3: Optional[float] = None,
) -> None:
    """Packmol 用入力ファイルを生成する。

    密度か数密度のいずれか一方を指定する。
    未指定量は相互変換により決定する。

    Args:
        packmol (Packmol):
        filename (str): 出力する Packmol 入力ファイル名。
        N_tot (int): セル内の総原子数。
        symbols (list): 元素
        ratios (list): 化学量論比
        rho_g_cm3 (float, optional): 密度 ρ [g/cm^3]。
        n_per_A3 (float, optional): 数密度 n [1/Å^3]。

    Raises:
        ValueError: 密度と数密度の両方が未指定の場合。
    """
    if symbols is None:
        symbols = ["Fe", "Si", "B"]

    # 化学量論比（整数比）
    if ratios is None:
        ratios = [80, 9, 11]

    #####################
    # 平均原子量の計算
    if n_per_A3 is None and rho_g_cm3 is None:
        raise ValueError("rho または n のどちらか一方を必ず指定してください。")

    if n_per_A3 is None:
        n_per_A3 = packmol.number_density_from_rho(symbols, ratios, rho_g_cm3)

    if rho_g_cm3 is None:
        rho_g_cm3 = packmol.rho_from_number_density(symbols, ratios, n_per_A3)

    #####################
    # Fe-Si-B の総原子数からそれぞれの原子数を決める
    # 化学量論比はすでに決定済み
    N_Fe, N_Si, N_B = compute_element_counts(N_tot)
    L = packmol.cell_length_from_number_density(N_tot, n_per_A3)

    with open(filename, "w") as f:
        f.write("tolerance 2.0\n")
        f.write("filetype xyz\n")
        f.write(f"output {result_xyz_file}\n\n")

        # Fe
        f.write(f"structure {Fe_xyz_file}\n")
        f.write(f"  number {N_Fe}\n")
        f.write(f"  inside box 0.0 0.0 0.0  {L:.6f} {L:.6f} {L:.6f}\n")
        f.write("end structure\n\n")

        # Si
        f.write(f"structure {Si_xyz_file}\n")
        f.write(f"  number {N_Si}\n")
        f.write(f"  inside box 0.0 0.0 0.0  {L:.6f} {L:.6f} {L:.6f}\n")
        f.write("end structure\n\n")

        # B
        f.write(f"structure {B_xyz_file}\n")
        f.write(f"  number {N_B}\n")
        f.write(f"  inside box 0.0 0.0 0.0  {L:.6f} {L:.6f} {L:.6f}\n")
        f.write("end structure\n")


def main() -> None:

    comment = "FeSiB amorphous generated by Packmol"
    PACKMOL = "/Users/nakada/packmol/bin/packmol"

    ##########################
    N_tot = 500  # セルの原子数
    rho = 7.35  # 質量密度
    ##########################

    pm = Packmol()
    write_packmol_input(
        packmol=pm,
        filename="packmol.inp",
        N_tot=N_tot,
        rho_g_cm3=rho,
        n_per_A3=None,
    )

    # --- structure file generation ---
    pm.write_single_atom_xyz("Fe.xyz", "Fe")
    pm.write_single_atom_xyz("Si.xyz", "Si")
    pm.write_single_atom_xyz("B.xyz", "B")

    # Packmol を自動実行
    pm.run_packmol(packmol_path=PACKMOL)

    # POSCAR
    pm.xyz_to_poscar(
        "FeSiB_amorphous.xyz",
        "POSCAR",
        comment=comment,
        elements=["Fe", "Si", "B"],
    )


if __name__ == "__main__":
    main()
