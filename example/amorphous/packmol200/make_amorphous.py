#!/usr/bin/env python3
"""
K.NAKADA, kengo.nakada@gmail.com
make_amorphous.py

Fe–Si–B アモルファス初期構造を Packmol により生成するための
入力ファイル (packmol.inp) を作成するスクリプト。

本スクリプトは、以下の 3 点を外部入力とする：

    1. 化学量論比（整数比）
    2. 密度 [g/cm^3] または 数密度 [1/Å^3] のいずれか一方
    3. セル内の総原子数 N_tot

Packmol は密度・化学量論比の概念を持たないため、本スクリプト側で
原子数とセル一辺長 L を計算し、Packmol 形式の inside box 指定に変換する。
"""
from typing import Any, Dict, List, Optional, Union, Tuple, Callable, Sequence
import shutil

from rmc_dft.packmol.packmol import Packmol
from x_logger import XLogger


def main() -> None:
    logger = XLogger()

    inp_file = "packmol.inp"
    comment = "FeSiB amorphous generated by Packmol"
    # PACKMOL = "/Users/nakada/packmol/bin/packmol"
    PACKMOL = "/home/hpc/packmol/bin/packmol"

    result_xyz_file = "FeSiB_amorphous.xyz"
    Fe_xyz_file = "Fe.xyz"
    Si_xyz_file = "Si.xyz"
    B_xyz_file = "B.xyz"

    ##########################
    N_tot = 200  # セルの原子数
    rho_g_cm3 = 7.35  # 質量密度
    ratios = [80, 9, 11]  # 化学量論比
    symbols = ["Fe", "Si", "B"]
    ##########################

    pm = Packmol()

    n_per_A3 = pm.number_density_from_rho(symbols, ratios, rho_g_cm3)
    # rho_g_cm3 = pm.rho_from_number_density(symbols, ratios, n_per_A3)

    # Fe-Si-B の総原子数からそれぞれの原子数を決める,化学量論比はすでに決定済み
    counts = pm.compute_element_counts(symbols, ratios, N_tot)
    N_Fe = counts["Fe"]
    N_Si = counts["Si"]
    N_B = counts["B"]
    L = pm.cell_length_from_number_density(N_tot, n_per_A3)

    logger.info(f"{counts}")
    logger.info(f"L = {L:.6f}")

    with open(inp_file, "w") as f:
        f.write("tolerance 2.3\n")  # 最小距離
        f.write("filetype xyz\n")
        f.write(f"output {result_xyz_file}\n\n")
        # f.write("seed 987654321\n\n")
        # f.write("seed 1234567\n")  # 乱数のシード（デフォルト値)

        # Fe
        f.write(f"structure {Fe_xyz_file}\n")
        f.write(f"  number {N_Fe}\n")
        f.write(f"  inside box 0.0 0.0 0.0  {L:.6f} {L:.6f} {L:.6f}\n")
        f.write("end structure\n\n")

        # Si
        f.write(f"structure {Si_xyz_file}\n")
        f.write(f"  number {N_Si}\n")
        f.write(f"  inside box 0.0 0.0 0.0  {L:.6f} {L:.6f} {L:.6f}\n")
        f.write("end structure\n\n")

        # B
        f.write(f"structure {B_xyz_file}\n")
        f.write(f"  number {N_B}\n")
        f.write(f"  inside box 0.0 0.0 0.0  {L:.6f} {L:.6f} {L:.6f}\n")
        f.write("end structure\n")

    # --- structure file generation ---
    pm.write_single_atom_xyz("Fe.xyz", "Fe")
    pm.write_single_atom_xyz("Si.xyz", "Si")
    pm.write_single_atom_xyz("B.xyz", "B")

    # Packmol を自動実行
    pm.run_packmol(packmol_bin=PACKMOL)

    # POSCAR
    pm.xyz_to_poscar(
        "FeSiB_amorphous.xyz",
        "POSCAR",
        comment=comment,
        elements=["Fe", "Si", "B"],
    )
    shutil.copyfile("POSCAR", "POSCAR0")
    shutil.copyfile("POSCAR", "POSCAR0.vasp")


if __name__ == "__main__":
    main()
